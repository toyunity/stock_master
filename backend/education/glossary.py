def read_temp(key, v) -> Optional[str]:
    """'코스피 온도' 판정 단어. 값이 없거나 모르는 키면 None(지어내지 않는다)."""
    bands = _TEMP_BANDS.get(key)
    if bands is None or v is None:
        return None
    for hi, word in bands:
        if hi is None or v < hi:
            return word
    return None


