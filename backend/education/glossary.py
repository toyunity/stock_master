GLOSSARY = {t.key: t for t in _TERMS}

def all_terms():
    """전체 용어 목록(정의된 순서)."""
    return list(_TERMS)

def get(key: str):
    """키로 용어 조회. 없으면 None."""
    return GLOSSARY.get(key)

def terms_in(text: str):
    """주어진 문자열에 등장하는 용어들을 (정의 순서로, 중복 없이) 반환."""
    found = []
    for t in _TERMS:
        names = (t.key,) + tuple(t.aliases)
        if any(n in text for n in names):
            found.append(t)
    # 더 구체적인 키의 부분문자열인 키는 제거 (예: 과매수가 있으면 매수는 빼기)
    found_keys = {t.key for t in found}
    found = [t for t in found
             if not any(t.key != other and t.key in other for other in found_keys)]
    return found
